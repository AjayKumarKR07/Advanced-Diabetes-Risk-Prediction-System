"""
backend/app/core/config.py
==========================
Configuration settings for the Advanced Diabetes Risk Prediction System API.
"""

from pathlib import Path
from typing import List
from pydantic_settings import BaseSettings, SettingsConfigDict

ROOT_DIR = Path(__file__).resolve().parent.parent.parent.parent


class Settings(BaseSettings):
    PROJECT_NAME: str = "Advanced Diabetes Risk Prediction System API"
    API_V1_STR: str = "/api"
    VERSION: str = "1.0.0"
    DESCRIPTION: str = (
        "Production-grade FastAPI backend serving the CDC BRFSS 2015 3-class diabetes "
        "risk prediction pipeline (Logistic Regression with balanced class weighting). "
        "Strictly an academic research prototype; NOT a clinical diagnostic device."
    )

    # Model & Artifact paths
    MODEL_PATH: Path = ROOT_DIR / "models" / "cdc" / "group_aware_benchmarks" / "LogisticRegression" / "model.pkl"
    METADATA_PATH: Path = ROOT_DIR / "models" / "cdc" / "group_aware_benchmarks" / "LogisticRegression" / "metadata.json"
    PHASE5_METRICS_PATH: Path = ROOT_DIR / "results" / "reports" / "phase5_final_metrics.json"

    # CORS origins
    CORS_ORIGINS: List[str] = [
        "http://localhost:3000",
        "http://localhost:5173",
        "http://127.0.0.1:3000",
        "http://127.0.0.1:5173",
        "*",  # Permissive for local dev
    ]

    # Mandatory disclaimer
    DISCLAIMER: str = (
        "RESEARCH PROTOTYPE ONLY: This assessment is generated by an academic research machine "
        "learning model trained on self-reported CDC BRFSS survey data. It is NOT a clinical "
        "diagnosis, does NOT replace laboratory diagnostic tests (such as HbA1c or fasting plasma "
        "glucose), and must NOT be used for autonomous clinical decision-making. Please consult a "
        "qualified healthcare professional for medical advice."
    )

    model_config = SettingsConfigDict(case_sensitive=True, env_file=".env", extra="ignore")


settings = Settings()

