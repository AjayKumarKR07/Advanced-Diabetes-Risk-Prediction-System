"""
backend/app/schemas/insights_schemas.py
=======================================
Pydantic schemas for personalized, explainable, educational health insights,
rule-based recommendations, and historical indicator comparisons (Phase 6.16 & Phase 6.16.1).
"""

from typing import Dict, List, Optional
from pydantic import BaseModel, Field


class EducationalRecommendation(BaseModel):
    id: str = Field(..., description="Unique rule/recommendation identifier")
    category: str = Field(..., description="Indicator domain (e.g. Metabolic & Body, Cardiovascular Health)")
    priority: str = Field(..., description="Priority tier: high, medium, info, or positive")
    observation: str = Field(..., description="Specific observation from user submitted data")
    indicator_name: str = Field(..., description="Relevant indicator name")
    indicator_value: str = Field(..., description="Submitted value in readable format")
    explanation: str = Field(..., description="Transparent scientific & educational background")
    suggestion: str = Field(..., description="Non-medical educational suggestion")
    reason: str = Field(..., description="Exact trigger condition for generating this recommendation")
    date_generated: str = Field(..., description="Date of assessment or evaluation")
    evidence_reference: Optional[str] = Field(
        None, description="Authoritative public health citation (e.g. CDC BRFSS, WHO, AHA/ACC)"
    )
    limitations: Optional[str] = Field(
        None, description="Scientific limitations of this self-reported survey indicator"
    )


class HistoricalComparisonItem(BaseModel):
    indicator: str = Field(..., description="Indicator name")
    previous_value: str = Field(..., description="Value in previous assessment")
    current_value: str = Field(..., description="Value in current assessment")
    change_type: str = Field(
        ...,
        description="Neutral change category: increased, decreased, stable, neutral, or conflicting",
    )
    observation: str = Field(..., description="Descriptive observation of the change")


class InsightsSummary(BaseModel):
    total_insights: int = 0
    high_priority_count: int = 0
    medium_priority_count: int = 0
    positive_habits_count: int = 0
    categories_breakdown: Dict[str, int] = Field(default_factory=dict)
    latest_assessment_id: Optional[int] = None
    latest_assessment_date: Optional[str] = None


class HealthInsightsResponse(BaseModel):
    assessment_id: Optional[int] = None
    assessment_date: Optional[str] = None
    total_assessments: int = 0
    summary: InsightsSummary
    recommendations: List[EducationalRecommendation] = Field(default_factory=list)
    historical_comparisons: List[HistoricalComparisonItem] = Field(default_factory=list)
    disclaimer: str = (
        "These educational insights are generated by a transparent rule-based algorithm from your "
        "self-reported survey responses. They are intended strictly for educational awareness and "
        "lifestyle reflection. They do NOT constitute medical advice, clinical diagnoses, or treatment plans. "
        "Never alter medication or therapy without consulting a licensed physician."
    )


class InsightsHistoryResponse(BaseModel):
    total_assessments: int = 0
    assessments_analyzed: int = 0
    comparisons: List[HistoricalComparisonItem] = Field(default_factory=list)
    disclaimer: str = (
        "Historical comparisons reflect changes in self-reported survey entries over time. "
        "They do not establish clinical disease progression or verified physiological outcomes."
    )
